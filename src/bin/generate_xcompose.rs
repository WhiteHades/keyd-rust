use std::fmt::Write as _;
use std::fs::{self, File};
use std::io::Write as _;
use std::path::PathBuf;

const DIGITS: &[u8; 36] = b"0123456789abcdefghijklmnopqrstuvwxyz";

fn codepoint(line: &str) -> Option<u32> {
    let field = line.split(';').next()?.trim();
    let field = field.strip_prefix('+').unwrap_or(field);
    let (field, prefixed) = match field
        .strip_prefix("0x")
        .or_else(|| field.strip_prefix("0X"))
    {
        Some(field) => (field, true),
        None => (field, false),
    };
    let mut code = 0u32;
    let mut digit = false;
    for (index, byte) in field.bytes().enumerate() {
        if byte == b'_' {
            if !digit && !(prefixed && index == 0) {
                return None;
            }
            digit = false;
        } else {
            code = code
                .checked_mul(16)?
                .checked_add((byte as char).to_digit(16)?)?;
            digit = true;
        }
    }
    (digit && code >= 128 && char::from_u32(code).is_some()).then_some(code)
}

fn render(codes: &[u32]) -> (String, String) {
    let mut compose = String::new();
    for (index, &code) in codes.iter().enumerate() {
        writeln!(
            compose,
            "<Cancel> <{}> <{}> <{}> : \"{}\"",
            DIGITS[index / (36 * 36) % 36] as char,
            DIGITS[index / 36 % 36] as char,
            DIGITS[index % 36] as char,
            char::from_u32(code).unwrap(),
        )
        .unwrap();
    }

    let mut runs: Vec<(u32, u32)> = Vec::new();
    for &code in codes {
        match runs.last_mut() {
            Some((_, end)) if code == *end + 1 => *end = code,
            _ => runs.push((code, code)),
        }
    }
    let mut source = String::from(
        "// GENERATED BY generate_xcompose, DO NOT MODIFY BY HAND.\n\nuse crate::keys::*;\n\n",
    );
    writeln!(
        source,
        "pub static UNICODE_TABLE: [u32; {}] = {{",
        codes.len()
    )
    .unwrap();
    source.push_str("    let runs: &[(u32, u32)] = &[\n");
    for (start, end) in runs {
        writeln!(source, "        ({start}, {end}),").unwrap();
    }
    writeln!(source, "    ];\n    let mut table = [0; {}];", codes.len()).unwrap();
    source.push_str(
        r#"    let mut i = 0;
    let mut n = 0;
    while i < runs.len() {
        let mut code = runs[i].0;
        while code <= runs[i].1 {
            table[n] = code;
            n += 1;
            code += 1;
        }
        i += 1;
    }
    assert!(n == table.len());
    table
};

pub fn unicode_lookup_index(codepoint: u32) -> i32 {
    UNICODE_TABLE
        .iter()
        .position(|&code| code == codepoint)
        .map_or(-1, |i| i as i32)
}

pub fn unicode_get_sequence(idx: u16) -> [u8; 4] {
    let chars = [
        KEYD_0, KEYD_1, KEYD_2, KEYD_3, KEYD_4, KEYD_5, KEYD_6, KEYD_7, KEYD_8, KEYD_9, KEYD_A,
        KEYD_B, KEYD_C, KEYD_D, KEYD_E, KEYD_F, KEYD_G, KEYD_H, KEYD_I, KEYD_J, KEYD_K, KEYD_L,
        KEYD_M, KEYD_N, KEYD_O, KEYD_P, KEYD_Q, KEYD_R, KEYD_S, KEYD_T, KEYD_U, KEYD_V, KEYD_W,
        KEYD_X, KEYD_Y, KEYD_Z,
    ];
    let idx = idx as usize;
    [
        KEYD_CANCEL,
        chars[idx / (36 * 36) % 36],
        chars[idx / 36 % 36],
        chars[idx % 36],
    ]
}
"#,
    );
    (compose, source)
}

struct StagedFile {
    destination: &'static str,
    path: PathBuf,
}

impl StagedFile {
    fn write(destination: &'static str, contents: &str) -> Result<Self, String> {
        let path = PathBuf::from(format!("{destination}.{}.tmp", std::process::id()));
        let mut file =
            File::create_new(&path).map_err(|error| format!("stage {destination}: {error}"))?;
        let staged = Self { destination, path };
        file.write_all(contents.as_bytes())
            .and_then(|()| file.sync_all())
            .map_err(|error| format!("stage {destination}: {error}"))?;
        Ok(staged)
    }

    fn replace(self) -> Result<(), String> {
        fs::rename(&self.path, self.destination)
            .map_err(|error| format!("replace {}: {error}", self.destination))
    }
}

impl Drop for StagedFile {
    fn drop(&mut self) {
        let _ = fs::remove_file(&self.path);
    }
}

fn run() -> Result<(), String> {
    let input = fs::read_to_string("data/unicode.txt")
        .map_err(|error| format!("read data/unicode.txt: {error}"))?;
    let codes: Vec<u32> = input.split(['\r', '\n']).filter_map(codepoint).collect();
    let (compose, source) = render(&codes);
    let compose = StagedFile::write("data/keyd.compose", &compose)?;
    let source = StagedFile::write("src/unicode.rs", &source)?;
    // shortcut: outputs commit separately, add recovery if cross-file crash consistency is required.
    compose.replace()?;
    source.replace()
}

fn main() -> std::process::ExitCode {
    match run() {
        Ok(()) => std::process::ExitCode::SUCCESS,
        Err(error) => {
            eprintln!("generate_xcompose: {error}");
            std::process::ExitCode::FAILURE
        }
    }
}
